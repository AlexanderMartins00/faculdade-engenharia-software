            saida += "ID do veículo: " + idVeiculo + "\n";
            saida += "Placa: " + placa.toUpperCase() + "\n";
            saida += "Descrição: " + descricao + "\n";
            saida += "Valor: " + valor + "\n";
            saida += "Data: " + data + "\n";

