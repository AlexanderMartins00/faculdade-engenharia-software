    private void mostrarDadosNatela() {
        try {
            DefaultTableModel model = (DefaultTableModel) jTableSaidaDadosGrid.getModel();
            model.setRowCount(0);

            ControleDespesas controle = new ControleDespesas();
            ArrayList<Despesas> atualizar = controle.listaDeTipoDasDespesas();

            for (Despesas obj : atualizar) {
                model.addRow(new Object[]{
                    obj.getIdTipoDeDespesa(),
                    obj.getDescricao()
                });
            }
        } catch (Exception e) {
        }
    }
