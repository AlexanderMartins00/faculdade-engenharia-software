            ArrayList<Movimentacao> lista = controleMovimentacao.listar();

            Document document = new Document();
            PdfWriter.getInstance(document, new FileOutputStream("relatorio_despesas_frota_mes.pdf"));
            document.open();

            document.add(new Paragraph("GYN LOG - Relatório de Despesas da Frota por Mês"));
            document.add(new Paragraph("Mês: " + Mes + " | Ano: " + anoEscolhido));
            document.add(new Paragraph(" "));
            document.add(new Paragraph("Lista de despesas da frota neste mês:"));
            document.add(new Paragraph(" "));

            PdfPTable tabela = new PdfPTable(4);
            tabela.addCell("ID Veículo");
            tabela.addCell("Data");
            tabela.addCell("Descrição");
            tabela.addCell("Valor (R$)");

