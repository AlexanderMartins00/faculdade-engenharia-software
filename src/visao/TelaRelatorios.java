    private void listarVeiculosComboBox() {
        try {
            ArrayList<Veiculos> lista = controle.listar();
            javax.swing.DefaultComboBoxModel<String> model = new javax.swing.DefaultComboBoxModel<>();

            for (Veiculos v : lista) {
                if (v.getStatus() == StatusVeiculo.ATIVO) {
                    model.addElement("ID: " + v.getIdVeiculo() + " / " + "PLACA: " + v.getPlaca().toUpperCase()
                            + " / " + "MODELO: " + v.getModelo());
                }
            }
            jComboBoxVeiculo.setModel(model);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro ao carregar Veiculos: " + e.getMessage());
        }
    }

    private void listarAnosComboBox() {
        try {
            ArrayList<Veiculos> lista = controle.listar();
            javax.swing.DefaultComboBoxModel<String> model = new javax.swing.DefaultComboBoxModel<>();

            int menorAno = lista.get(0).getAnoDeFabricacao();
            for (int cont = 1; cont < lista.size(); cont++) {
                Veiculos v = lista.get(cont);
                int anoVeiculo = v.getAnoDeFabricacao();
                if (anoVeiculo < menorAno) {
                    menorAno = anoVeiculo;
                }
            }
            int anoAtual = 2025;
            for (int cont = menorAno; cont <= anoAtual; cont++) {
                model.addElement(String.valueOf(cont));
            }

            jComboBoxAno.setModel(model);

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro ao carregar anos: " + e.getMessage());
        }
    }

