    private void jButtonBuscarVeiculoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonBuscarVeiculoActionPerformed
        // TODO add your handling code here:

        try {
            int idVeiculo = Integer.parseInt(jTextFieldIdVeiculo.getText());

            Veiculos objVeiculos = controle.buscarPorId(idVeiculo);

            String placa = objVeiculos.getPlaca();
            String marca = objVeiculos.getMarca();
            String modelo = objVeiculos.getModelo();
            int anoFab = objVeiculos.getAnoDeFabricacao();
            StatusVeiculo status = objVeiculos.getStatus();

            String saida = "";
            saida += "ID do veículo: " + idVeiculo + "\n";
            saida += "Placa: " + placa.toUpperCase() + "\n";
            saida += "Marca: " + marca.toUpperCase() + "\n";
            saida += "Modelo: " + modelo.toUpperCase() + "\n";
            saida += "Ano de fabricação: " + anoFab + "\n";
            saida += "Status do veículo: " + status.toString().toUpperCase();

            JOptionPane.showMessageDialog(rootPane, saida);
            jTextFieldIdVeiculo.setText(null);
            jTextFieldAnoDeFabricacao.setText(null);
            jTextFieldMarca.setText(null);
            jTextFieldModelo.setText(null);
            jTextFieldPlaca.setText(null);

        } catch (Exception e) {
            JOptionPane.showMessageDialog(rootPane, "Erro: " + e.getMessage());
        }

    }//GEN-LAST:event_jButtonBuscarVeiculoActionPerformed

    private void jButtonEditarVeiculoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonEditarVeiculoActionPerformed
        // TODO add your handling code here:

        try {
            int linha = jTableSaidaNaGridVeiculo.getSelectedRow();

            int idVeiculo = Integer.parseInt(jTextFieldIdVeiculo.getText().trim());
            String placa = jTextFieldPlaca.getText().trim();
            String marca = jTextFieldMarca.getText().trim();
            String modelo = jTextFieldModelo.getText().trim();
            int anoFabricacao = Integer.parseInt(jTextFieldAnoDeFabricacao.getText().trim());
            StatusVeiculo statusVeiculo = StatusVeiculo.valueOf(jComboBoxRegistro.getSelectedItem().toString());

            DefaultTableModel model = (DefaultTableModel) jTableSaidaNaGridVeiculo.getModel();
            model.setValueAt(idVeiculo, linha, 0);
            model.setValueAt(placa, linha, 1);
            model.setValueAt(marca, linha, 2);
            model.setValueAt(modelo, linha, 3);
            model.setValueAt(anoFabricacao, linha, 4);
            model.setValueAt(statusVeiculo, linha, 5);
            
            Veiculos objVeiculo = new Veiculos(idVeiculo, placa, marca, modelo, anoFabricacao, statusVeiculo);
            controle.atualizar(objVeiculo);

            jTextFieldIdVeiculo.setText(null);
            jTextFieldAnoDeFabricacao.setText(null);
            jTextFieldMarca.setText(null);
            jTextFieldModelo.setText(null);
            jTextFieldPlaca.setText(null);

        } catch (Exception erro) {
            JOptionPane.showMessageDialog(rootPane, erro.getMessage());
        }
    }//GEN-LAST:event_jButtonEditarVeiculoActionPerformed

    private void jTableSaidaNaGridVeiculoMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTableSaidaNaGridVeiculoMouseClicked
        // TODO add your handling code here:

        int linha = jTableSaidaNaGridVeiculo.getSelectedRow();

        if (linha >= 0) {
            String id = jTableSaidaNaGridVeiculo.getValueAt(linha, 0) + "";
            String placa = jTableSaidaNaGridVeiculo.getValueAt(linha, 1) + "";
            String marca = jTableSaidaNaGridVeiculo.getValueAt(linha, 2) + "";
            String modelo = jTableSaidaNaGridVeiculo.getValueAt(linha, 3) + "";
            String anoFab = jTableSaidaNaGridVeiculo.getValueAt(linha, 4) + "";
            String status = jTableSaidaNaGridVeiculo.getValueAt(linha, 5) + "";

            jTextFieldIdVeiculo.setText(id);
            jTextFieldPlaca.setText(placa);
            jTextFieldMarca.setText(marca);
            jTextFieldModelo.setText(modelo);
            jTextFieldAnoDeFabricacao.setText(anoFab);
            jComboBoxRegistro.setSelectedItem(status);
        }

    }//GEN-LAST:event_jTableSaidaNaGridVeiculoMouseClicked

