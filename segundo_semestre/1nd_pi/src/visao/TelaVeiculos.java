    private void mostrarDadosNaTela() {
        try {
            DefaultTableModel model = (DefaultTableModel) jTableSaidaNaGridVeiculo.getModel();
            model.setRowCount(0);

            ArrayList<Veiculos> listar = controle.listar();

            for (Veiculos obj : listar) {
                model.addRow(new Object[]{
                    obj.getIdVeiculo(),
                    obj.getPlaca().toUpperCase(),
                    obj.getMarca(),
                    obj.getModelo(),
                    obj.getAnoDeFabricacao(),
                    obj.getStatus()
                });
            }
        } catch (Exception e) {
        }
    }
